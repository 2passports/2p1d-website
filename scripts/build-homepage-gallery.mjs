#!/usr/bin/env node
// Builds the homepage rotating photo wall from the original DylanAdriana####
// photos in public/images.
//
// Why this exists: most originals are camera RAW (.DNG, 50 to 80 MB each) or
// .heic, which browsers cannot display and the Next.js image optimiser cannot
// decode. This script makes a web-sized, metadata-free JPG copy of each one in
// public/images/gallery (same base name, .jpg extension) and regenerates the
// image list in src/app/data/homepageGallery.ts. Originals are never modified.
//
// Requirements: macOS (uses the built-in `sips` to decode RAW and HEIC) and
// `sharp`, which ships with Next.js.
//
// Usage: node scripts/build-homepage-gallery.mjs
// Re-run it whenever photos are added or removed. Existing gallery JPGs are
// reused, so only new photos are converted.

import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import sharp from 'sharp'

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..')
const srcDir = path.join(root, 'public/images')
const outDir = path.join(srcDir, 'gallery')
const manifestPath = path.join(root, 'src/app/data/homepageGallery.ts')

const MAX_EDGE = 1800
const SOURCE_PATTERN = /^DylanAdriana\d.*\.(dng|jpe?g|png|webp|heic|heif|avif|tiff?)$/i

const sources = fs
  .readdirSync(srcDir)
  .filter((f) => SOURCE_PATTERN.test(f))
  .sort((a, b) => a.localeCompare(b, 'en', { numeric: true }))

fs.mkdirSync(outDir, { recursive: true })
const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'gallery-'))
const outputs = []

for (const file of sources) {
  const base = file.replace(/\.[^.]+$/, '')
  const outName = `${base}.jpg`
  const outPath = path.join(outDir, outName)
  outputs.push(outName)
  if (fs.existsSync(outPath)) continue

  const input = path.join(srcDir, file)
  const tmp = path.join(tmpDir, 'decoded.jpg')
  execFileSync('sips', ['-s', 'format', 'jpeg', '-s', 'formatOptions', '95', input, '--out', tmp], { stdio: 'ignore' })

  // sips copies the camera Orientation tag across without rotating the pixels,
  // so .rotate() bakes the correct rotation in. sharp then drops all EXIF
  // (including GPS location) by default, which matters because these files
  // are publicly reachable under /images/gallery.
  await sharp(tmp)
    .rotate()
    .resize(MAX_EDGE, MAX_EDGE, { fit: 'inside', withoutEnlargement: true })
    .jpeg({ quality: 80, mozjpeg: true })
    .toFile(outPath)
  console.log(`converted ${file}`)
}

fs.rmSync(tmpDir, { recursive: true, force: true })

// Remove gallery JPGs whose original has gone.
for (const f of fs.readdirSync(outDir)) {
  if (!outputs.includes(f)) {
    fs.rmSync(path.join(outDir, f))
    console.log(`removed stale ${f}`)
  }
}

const manifest = `// Generated by scripts/build-homepage-gallery.mjs. Do not edit by hand.
// Web-sized copies of the DylanAdriana#### photos, used by the homepage
// rotating photo wall. Re-run the script after adding or removing photos.

export const homepageGalleryPhotos: string[] = [
${outputs.map((f) => `  '/images/gallery/${f}',`).join('\n')}
]
`
fs.writeFileSync(manifestPath, manifest)
console.log(`${outputs.length} photos in gallery, manifest written to ${path.relative(root, manifestPath)}`)
